/**
 * Generates the firmware's theme and sample reading from the web app's own
 * source, so the two cannot drift.
 *
 * Node 24 strips the TypeScript types on import, so this reads src/lib/*.ts
 * directly rather than a copy. Run with `npm run gen:firmware`.
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const { COLOR, PANEL, INSIGHT_GRADIENT } = await import(`${ROOT}/src/lib/tokens.ts`);
const { SAMPLE } = await import(`${ROOT}/src/lib/data.ts`);

const BANNER = `// GENERATED by scripts/gen-firmware-data.mjs — do not edit.
// Source of truth: src/lib/tokens.ts and src/lib/data.ts. Run \`npm run gen:firmware\`.
`;

const upperSnake = (name) => name.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toUpperCase();
const hex = (css) => `0x${css.replace("#", "").toUpperCase()}`;
const f = (n) => `${Number.isInteger(n) ? `${n}.0` : n}f`;
const cstr = (s) => `"${s.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
const optional = (s) => (s === undefined ? "nullptr" : cstr(s));

// ---------------------------------------------------------------- Theme.h
const gradient = INSIGHT_GRADIENT.match(/(\d+)deg,\s*(#[0-9A-Fa-f]{6})[^,]*,\s*(#[0-9A-Fa-f]{6})/);

const theme = `${BANNER}#pragma once
#include <stdint.h>

/** Every colour and metric the design uses, in one place. */
namespace theme {

// Panel geometry, in the design's own pixels.
inline constexpr int PANEL_WIDTH = ${PANEL.width};
inline constexpr int PANEL_HEIGHT = ${PANEL.height};
inline constexpr int PANEL_PADDING = ${PANEL.padding};

${Object.entries(COLOR)
  .map(([name, value]) => `inline constexpr uint32_t ${upperSnake(name)} = ${hex(value)};`)
  .join("\n")}

// The insight header runs this gradient. LVGL 9 can angle a gradient; on 8 it
// has to be horizontal, which is close enough at this size.
inline constexpr uint32_t INSIGHT_GRADIENT_FROM = ${hex(gradient?.[2] ?? "#15897E")};
inline constexpr uint32_t INSIGHT_GRADIENT_TO = ${hex(gradient?.[3] ?? "#0E4C86")};
inline constexpr int INSIGHT_GRADIENT_DEGREES = ${gradient?.[1] ?? 120};

}  // namespace theme
`;

// ----------------------------------------------------------- SampleData.h
const ICONS = {
  hotWater: "HotWater",
  tumbleDryer: "TumbleDryer",
  oven: "Oven",
  hob: "Hob",
  lighting: "Lighting",
};

const floatArray = (name, values) =>
  `inline constexpr float ${name}[] = {\n    ${values.map(f).join(", ")}};`;

const homeStruct = (key, data) => {
  const live = data.live ? `&k${key}Live` : "nullptr";
  const averages = data.averages ? `&k${key}Averages` : "nullptr";
  const p = data.progress;
  return `    {${cstr(data.title)}, ${optional(data.badge)}, ${live}, ${averages},
     {${cstr(p.month)}, ${f(p.estimateKwh)}, ${f(p.usedKwh)}, ${cstr(p.caption)}, ${p.closed}}}`;
};

const compareStruct = (data, chipsName) =>
  `    {${optional(data.eyebrow)}, ${cstr(data.subtitle)}, ${cstr(data.unitLabel)},
     ${f(data.myKwh)}, ${f(data.theirKwh)}, ${chipsName}, ${data.chips.length}, ${data.groupSize}}`;

// Every character the UI can show, so the font subset can be exact rather than
// "all of Latin-1 and hope".
const glyphs = new Set();
const walk = (value) => {
  if (typeof value === "string") for (const ch of value) glyphs.add(ch);
  else if (Array.isArray(value)) value.forEach(walk);
  else if (value && typeof value === "object") Object.values(value).forEach(walk);
};
walk(SAMPLE);
for (const ch of "0123456789,.%+-/() kWhm²") glyphs.add(ch);
const subset = [...glyphs].filter((c) => c !== "\n").sort().join("");

const data = `${BANNER}#pragma once
#include "MeterData.h"

/**
 * The reading the design was drawn against.
 *
 * Font subset — every character below appears in this data, so lv_font_conv
 * can be given exactly this range and nothing more:
 * ${cstr(subset)}
 */
namespace sample {

${floatArray("kCurrentDaily", SAMPLE.medium.daily)}
${floatArray("kPreviousDaily", SAMPLE.mediumPrev.daily)}
${floatArray("kCurrentYear", SAMPLE.high.monthly)}
${floatArray("kPreviousYear", SAMPLE.highPrev.monthly)}

inline constexpr LiveReading kHomeLive = {${f(SAMPLE.home.live.kw)}, ${f(SAMPLE.home.live.scaleKw)}, ${cstr(SAMPLE.home.live.caption)}};
inline constexpr PeriodAverages kHomePrevAverages = {${f(SAMPLE.homePrev.averages.kw)}, ${f(SAMPLE.homePrev.averages.kwhPerDay)}};

inline constexpr Appliance kAppliances[] = {
${SAMPLE.appliances.items
  .map((a) => `    {${cstr(a.name)}, ApplianceIcon::${ICONS[a.id]}, ${f(a.kwh)}, ${f(a.share)}}`)
  .join(",\n")}};

inline constexpr const char* kCompareChips[] = {
${SAMPLE.compare.chips.map((c) => `    ${cstr(c)}`).join(",\n")}};

inline constexpr TelegramLine kTelegramLines[] = {
${SAMPLE.telegram.lines.map((l) => `    {${cstr(l.code)}, ${cstr(l.gloss)}}`).join(",\n")}};

inline constexpr MeterSnapshot kSnapshot = {
${homeStruct("Home", SAMPLE.home)},
${homeStruct("HomePrev", SAMPLE.homePrev)},
    {${cstr(SAMPLE.appliances.headline)}, ${cstr(SAMPLE.appliances.intro)},
     kAppliances, ${SAMPLE.appliances.items.length}},
    {${cstr(SAMPLE.medium.title)}, kCurrentDaily, ${SAMPLE.medium.daily.length}, ${SAMPLE.medium.daysInMonth}},
    {${cstr(SAMPLE.mediumPrev.title)}, kPreviousDaily, ${SAMPLE.mediumPrev.daily.length}, ${SAMPLE.mediumPrev.daysInMonth}},
    {${cstr(SAMPLE.high.title)}, kCurrentYear, ${SAMPLE.high.monthly.length}},
    {${cstr(SAMPLE.highPrev.title)}, kPreviousYear, ${SAMPLE.highPrev.monthly.length}},
${compareStruct(SAMPLE.compare, "kCompareChips")},
${compareStruct(SAMPLE.comparePrev, "kCompareChips")},
    {kTelegramLines, ${SAMPLE.telegram.lines.length}, ${cstr(SAMPLE.telegram.highlight)}}};

}  // namespace sample
`;

for (const [path, contents] of [
  ["firmware/src/ui/Theme.h", theme],
  ["firmware/src/data/SampleData.h", data],
]) {
  const full = `${ROOT}/${path}`;
  mkdirSync(dirname(full), { recursive: true });
  writeFileSync(full, contents);
  console.log(`wrote ${path}`);
}
